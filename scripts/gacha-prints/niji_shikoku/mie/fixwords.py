"""三重大学の指示文を、過去問と一致しない自前の言い回しにそろえる（全ラウンド共通）"""
import sys, pathlib
REP = [
 ("下線部 (1) は、どのような状況を指しているか。", "下線部 (1) が表している家庭の様子を、"),
 ("永遠に扉を閉じるかの二つだけではないことを示しているのである。", "永遠に扉を閉じるかの二択に限られないと教えてくれる。"),
 ("のたとえで、筆者が紹介している人々が言おうとしていることを、", "のたとえに込められた、第4段落の人々の考えを、"),
]
for f in sys.argv[1:]:
    p = pathlib.Path(f); s = p.read_text(); n0 = s
    for a, b in REP: s = s.replace(a, b)
    if s != n0: p.write_text(s); print('fixed', f)
