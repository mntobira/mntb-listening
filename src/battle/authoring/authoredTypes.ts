/**
 * ===================================================================
 * 手で書き起こした対戦問題（authored）の型
 * ===================================================================
 *
 * このファイルは「別の作業場（別ルーム）の AI が書いた JSON」の形を決める。
 *
 * -------------------------------------------------------------------
 * ■ なぜこれが要るのか
 * -------------------------------------------------------------------
 * 対戦プールは今まで `scripts/gen-battle-pool.mts` が
 * 元データから ★機械的に★ 作っていた。その結果こうなっている（実測）。
 *
 *     化学基礎  小問 984 件 → 対戦に出ているのは 159 件（16%）
 *
 * 落ちている 825 件の内訳（実測・scripts/verify-authored-battle.mts が再現する）:
 *
 *     270  短答で答えが漢字     → 五十音キーボードに載らない
 *     168  短答で答えが式・記号
 *     115  記述                 → 生成器が最初から見ない
 *     107  選択式だが「何を答えるか画面から読み取れない」
 *     100  短答で答えが数値
 *      14  並べ替え
 *      ほか
 *
 * これらは ★問題が悪いのではない★。
 * 「大問のリード文＋小問」という形が、そのままでは対戦の1画面に載らないだけである。
 *
 * 過去に一度、機械的に4択へ変換する処理（word / panel）を書いて失敗した。
 * 失敗の原因ははっきりしている（gen-battle-pool.mts の USE_SYNTHESIZED_FORMATS 参照）。
 *
 *     ・誤答を「同じ章の他の設問の正解」から借りた → 借りた誤答が実は正しかった
 *     ・リード文を切り出したら前提の文が消えた   → 答えが一意でなくなった
 *     ・表記ゆれを1つに固定できなかった
 *
 * ★これは「変換」が悪いのではなく「読まずに借りた」ことが悪い。★
 * 問題を読んだうえで、誤答を意図して作るのはまったく別の作業である。
 * このファイルは、その「読んで書いた結果」を受け取るための型。
 *
 * -------------------------------------------------------------------
 * ■ 機械生成との関係
 * -------------------------------------------------------------------
 * 置き換えではなく ★追加★ である。
 *
 *     対戦プール = 機械生成（元データが選択肢を持つ設問）
 *                + authored（人／AI が読んで書き起こした設問）
 *
 * 同じ小問から両方できた場合は authored を優先する（人が読んだほうが正確）。
 * 判定は `source` の3つの ID の組で行う。
 *
 * -------------------------------------------------------------------
 * ■ ★選択肢は「配列の順番」で正解を持たない★
 * -------------------------------------------------------------------
 * 各選択肢が `correct: true` を自分で持つ。理由は2つ。
 *
 *   1. 書く人が「正解を何番目に置くか」を考えなくてよい
 *      （人が書くと正解が2番目に偏ることが知られている。
 *        生成器が ID から決まる順で並べ替えるので偏りが消える）
 *   2. 誤答の解説（why）が選択肢本体にくっつくので、
 *      並べ替えても対応がずれない
 *
 * -------------------------------------------------------------------
 * ■ ★why を必須にしている理由★
 * -------------------------------------------------------------------
 * 「なぜその誤答を置いたか」を書けない誤答は、たいてい根拠がない。
 * 書かせることで「借りてきただけの誤答」を弾ける。
 *
 * さらにこれは、対戦のあとに出す「なぜ間違えたか」の材料になる。
 * ベネッセ面談で出た「どこでつまずいたかより ★なぜ★ つまずいたか」に
 * 直接つながるのがこの欄である。
 *
 * -------------------------------------------------------------------
 * ■ このファイルは何も import しない
 * -------------------------------------------------------------------
 * 型だけを持つ葉モジュールにしておく。
 * 検証スクリプト（Node）も画面（ブラウザ）も同じ型を見られるようにするため。
 */

/** 手書き問題で使える出題形式（機械生成の BattleAnswerFormat の部分集合） */
export type AuthoredFormat = 'choice4' | 'choice' | 'kana';

/**
 * 選択肢1つ。
 *
 * `correct` は正解にだけ true を付ける。1問にちょうど1つ。
 * `why` は「なぜこれが正解か／なぜこれが誤りか」を1文で書く。★全選択肢に必須★
 */
export interface AuthoredOption {
  text: string;
  correct?: boolean;
  why: string;
}

/** その問題がどの既存の小問から来ているか */
export interface AuthoredSource {
  chapterId: string;
  problemId: string;
  subQuestionId: string;
}

/**
 * 手で書き起こした対戦問題1問。
 *
 * ★「新しい問題」ではなく「既存の大問を、対戦の1画面で解ける大きさに割った問題」★
 * である。元の小問が聞いている内容から離れてはいけない。
 */
export interface AuthoredQuestion {
  /**
   * 一意なID。`a:<chapterId>:<problemId>:<subQuestionId>:<連番>` の形。
   * 先頭の `a:` は authored の意味で、機械生成の `q:` / `k:` と衝突しない。
   */
  id: string;

  /** 元の小問。3つとも実データに存在しなければ検証で落ちる */
  source: AuthoredSource;

  format: AuthoredFormat;

  /**
   * 対戦画面に出す問題文（リード文にあたる部分）。
   *
   * ★これ単体＋label で答えが決まること。★
   * 「上の文章の」「次の図の」のように、画面に無いものを指してはいけない。
   * 150文字以内。
   */
  prompt: string;

  /** 設問文。「(1) 空気はどれか」など。空でもよいが prompt と両方空は不可 */
  label: string;

  /** choice4 / choice のとき必須。2〜6個。kana のときは空か省略 */
  options?: AuthoredOption[];

  /** kana のとき必須。カタカナ2〜8文字。choice系のときは省略 */
  answer?: string;

  /** kana のときの「なぜそれが答えか」1文（choice系は options[].why が担う） */
  answerWhy?: string;

  /**
   * 試合後に出す1行解答。
   * 「答えそのもの＋ひと言の理由」を 10〜120 文字で。
   * ★ここが対戦（①）と演習（②）をつなぐ橋の入口になる。★
   */
  oneLine: string;

  /**
   * 制限時間（秒）。8〜30。
   * 迷ったら choice=13 / choice4=15 / kana=18 を目安にする。
   */
  timeLimit: number;

  /**
   * 元データの本文・解説から答えの根拠が自動で見つからないときに、
   * ★元データから一字一句そのまま★ 引用して根拠を示す欄。
   *
   * 検証スクリプトは、この文字列が元の大問の本文・解説・解答のどこかに
   * 実在するかを照合する。実在しなければ落ちる。
   * 「読まずに書いた」問題をここで止めるための欄である。
   */
  grounding?: string;
}

/** 1章ぶんのファイルの中身 */
export interface AuthoredFile {
  subject: string;
  chapterId: string;
  /** 書いた作業場の名前。誰が書いたかを残すだけで、動作には影響しない */
  authoredBy?: string;
  questions: AuthoredQuestion[];
}
